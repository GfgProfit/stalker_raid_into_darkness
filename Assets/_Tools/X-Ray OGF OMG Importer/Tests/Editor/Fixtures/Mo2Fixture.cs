using System.Collections.Generic;
using System.Text;
using XRay.Importer.Sources.Vfs;

namespace XRay.Importer.Tests
{
    public sealed class Mo2Fixture
    {
        public const string MO2_FOLDER = "MO2";
        public const string BASE_FOLDER = "base_gamedata";

        private readonly TestDirectory _directory;

        public Mo2Fixture(TestDirectory directory)
        {
            _directory = directory;
            Mo2Root = directory.Combine(MO2_FOLDER);
            BaseFolder = directory.Combine(BASE_FOLDER);
            System.IO.Directory.CreateDirectory(BaseFolder);
            System.IO.Directory.CreateDirectory(directory.Combine(MO2_FOLDER + "/mods"));
            System.IO.Directory.CreateDirectory(directory.Combine(MO2_FOLDER + "/overwrite"));
        }

        public string Mo2Root { get; }
        public string BaseFolder { get; }

        public void WriteIni(string selectedProfile, params string[] settingsLines)
        {
            var builder = new StringBuilder();
            builder.Append("[General]\n");
            builder.Append("gameName=STALKER Anomaly\n");
            builder.Append("selected_profile=@ByteArray(").Append(EscapeByteArray(selectedProfile)).Append(")\n");
            builder.Append("version=2.5.2\n\n");
            builder.Append("[PluginPersistance]\nPython%20Proxy\\tryInit=false\n\n");
            builder.Append("[Settings]\n");
            foreach (string line in settingsLines)
            {
                builder.Append(line).Append('\n');
            }

            _directory.WriteText(MO2_FOLDER + "/ModOrganizer.ini", builder.ToString());
        }

        public void AddProfile(string name, params string[] modListLines)
        {
            var lines = new List<string> { "# This file was automatically generated by Mod Organizer." };
            lines.AddRange(modListLines);
            _directory.WriteText(MO2_FOLDER + "/profiles/" + name + "/modlist.txt", string.Join("\r\n", lines) + "\r\n");
        }

        public string AddModFile(string mod, string gamedataRelative, byte[] data)
        {
            return _directory.WriteFile(MO2_FOLDER + "/mods/" + mod + "/gamedata/" + gamedataRelative, data);
        }

        public string AddModRootFile(string mod, string relative, byte[] data)
        {
            return _directory.WriteFile(MO2_FOLDER + "/mods/" + mod + "/" + relative, data);
        }

        public string AddOverwriteFile(string gamedataRelative, byte[] data)
        {
            return _directory.WriteFile(MO2_FOLDER + "/overwrite/gamedata/" + gamedataRelative, data);
        }

        public string AddBaseFile(string gamedataRelative, byte[] data)
        {
            return _directory.WriteFile(BASE_FOLDER + "/" + gamedataRelative, data);
        }

        public XRaySourceConfiguration CreateConfiguration(string profile)
        {
            return new XRaySourceConfiguration { Mode = XRaySourceMode.Mo2AndBaseAnomaly, Mo2Folder = Mo2Root, Mo2Profile = profile, BaseAnomalyFolder = BaseFolder, IncludeGameGamedata = false };
        }

        public static string EscapeByteArray(string value)
        {
            var builder = new StringBuilder();
            bool escapeNextHex = false;
            foreach (byte b in Encoding.UTF8.GetBytes(value))
            {
                bool isHexDigit = (b >= '0' && b <= '9') || (b >= 'a' && b <= 'f') || (b >= 'A' && b <= 'F');
                if (b >= 0x80 || (escapeNextHex && isHexDigit))
                {
                    builder.Append("\\x").Append(b.ToString("x2"));
                    escapeNextHex = true;
                }
                else
                {
                    builder.Append(b == '\\' ? "\\\\" : ((char)b).ToString());
                    escapeNextHex = false;
                }
            }

            return builder.ToString();
        }
    }
}
